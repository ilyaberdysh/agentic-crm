-- Calls (slice 10; BACKLOG 10.09–10.11, 10.13–10.15; I calls §4, §6, §11; decisions in
-- research/architecture/decisions/slice10-calls.md). Built on the slice-7 transcript-only call recordings (0700):
--   call_recordings            + processing state, long / concise summaries, search text, duration
--   call_speakers              one per distinct speaker of a recording (email, else name), mapped to a meeting
--                              participant by email (X-28); utterances = call_transcript_segments (+ speaker_id)
--   insight_templates          named list of sections, versioned as snapshots (draft → active on publish, B.20)
--   insight_template_snapshots draft / active / superseded / discarded
--   insight_template_sections  type (plaintext | list), order, title + prompt as rich-text documents (B.10)
--   insight_template_previews  a draft rendered against a completed call (editor preview pane)
--   call_insights              a template snapshot applied to a call (generated by the LLM; credit cost)
--   member_call_settings       the member's default insight template
-- Actors on these cold tables are jsonb {type, id} (migration 0200 convention).

ALTER TABLE call_recordings
  -- Summaries (I calls §6.1): long (call page) and concise (record pages, cards). null status = never processed.
  ADD COLUMN summary text,
  ADD COLUMN summary_status text CHECK (summary_status IN ('queued', 'executing', 'completed', 'failed')),
  ADD COLUMN concise_summary text,
  ADD COLUMN concise_summary_status text
    CHECK (concise_summary_status IN ('queued', 'executing', 'completed', 'failed')),
  -- Why summaries failed ('AI_NOT_CONFIGURED', 'LLM_ERROR: …'); the call itself still completes.
  ADD COLUMN processing_error text,
  ADD COLUMN processed_at timestamptz,
  -- Every utterance's speech joined by newlines: the `query` search of the Calls list (trigram index below).
  ADD COLUMN transcript_text text NOT NULL DEFAULT '',
  -- sha256 of the imported transcript: a retried import of the same transcript into the same meeting is a replay.
  ADD COLUMN transcript_hash text,
  ADD COLUMN segment_count integer NOT NULL DEFAULT 0,
  -- Last utterance end (seconds); the call's length when the meeting has no better one.
  ADD COLUMN duration_seconds double precision NOT NULL DEFAULT 0,
  ADD COLUMN updated_at timestamptz NOT NULL DEFAULT now(),
  ADD COLUMN deleted_by jsonb;

CREATE INDEX call_recordings_workspace ON call_recordings (workspace_id, created_at) WHERE deleted_at IS NULL;
CREATE INDEX call_recordings_hash ON call_recordings (meeting_id, transcript_hash) WHERE deleted_at IS NULL;
CREATE INDEX call_recordings_text ON call_recordings USING gin (transcript_text gin_trgm_ops) WHERE deleted_at IS NULL;
CREATE INDEX meetings_title_trgm ON meetings USING gin (title gin_trgm_ops) WHERE deleted_at IS NULL;

CREATE TABLE call_speakers (
  id uuid PRIMARY KEY,
  workspace_id uuid NOT NULL REFERENCES workspaces (id),
  recording_id uuid NOT NULL REFERENCES call_recordings (id),
  position integer NOT NULL,                  -- order of first appearance
  name text NOT NULL,                         -- as provided by the importer
  email_address text,                         -- normalised
  participant_id uuid,                        -- meeting participant matched by email (automatic mapping)
  manual_participant_id uuid,                 -- reserved: manual re-mapping (no UI yet, I calls §9.8); wins when set
  member_id uuid,                             -- workspace member behind the participant or the address
  UNIQUE (recording_id, position)
);
CREATE INDEX call_speakers_recording ON call_speakers (recording_id, position);
CREATE INDEX call_speakers_participant ON call_speakers (participant_id) WHERE participant_id IS NOT NULL;

ALTER TABLE call_transcript_segments ADD COLUMN speaker_id uuid REFERENCES call_speakers (id);

-- Backfill: speakers of the recordings imported before this migration (one per address, else per name).
DO $$
DECLARE r record;
BEGIN
  FOR r IN
    SELECT DISTINCT ON (s.recording_id, coalesce(s.speaker_email, 'name:' || s.speaker_name))
      s.recording_id, s.workspace_id, s.speaker_name, s.speaker_email, s.participant_id, s.position
    FROM call_transcript_segments s
    ORDER BY s.recording_id, coalesce(s.speaker_email, 'name:' || s.speaker_name), s.position
  LOOP
    WITH ins AS (
      INSERT INTO call_speakers (id, workspace_id, recording_id, position, name, email_address, participant_id)
      VALUES (uuidv7(), r.workspace_id, r.recording_id, r.position, r.speaker_name, r.speaker_email, r.participant_id)
      RETURNING id
    )
    UPDATE call_transcript_segments s SET speaker_id = (SELECT id FROM ins)
    WHERE s.recording_id = r.recording_id
      AND coalesce(s.speaker_email, 'name:' || s.speaker_name) = coalesce(r.speaker_email, 'name:' || r.speaker_name);
  END LOOP;
  UPDATE call_recordings c SET
    transcript_text = coalesce((SELECT string_agg(s.speech, E'\n' ORDER BY s.position)
                                FROM call_transcript_segments s WHERE s.recording_id = c.id), ''),
    segment_count = (SELECT count(*) FROM call_transcript_segments s WHERE s.recording_id = c.id),
    duration_seconds = coalesce((SELECT max(s.end_time) FROM call_transcript_segments s WHERE s.recording_id = c.id), 0);
END
$$;

CREATE TABLE insight_templates (
  id uuid PRIMARY KEY,                        -- client-minted ("New template")
  workspace_id uuid NOT NULL REFERENCES workspaces (id),
  title text,                                 -- null → ai_title → "Untitled Template"
  ai_title text,
  status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'enabled', 'disabled')),
  -- Transient from creation until its first content edit (B.21): hidden from the list.
  is_transient boolean NOT NULL DEFAULT true,
  sort_order text COLLATE "C" NOT NULL,
  first_enabled_at timestamptz,
  archived_at timestamptz,
  created_by jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz
);
CREATE INDEX insight_templates_order ON insight_templates (workspace_id, sort_order, id) WHERE deleted_at IS NULL;

CREATE TABLE insight_template_snapshots (
  id uuid PRIMARY KEY,
  workspace_id uuid NOT NULL REFERENCES workspaces (id),
  template_id uuid NOT NULL REFERENCES insight_templates (id),
  parent_snapshot_id uuid REFERENCES insight_template_snapshots (id),
  status text NOT NULL CHECK (status IN ('draft', 'active', 'superseded', 'discarded')),
  first_touched_at timestamptz,
  last_touched_at timestamptz,
  published_at timestamptz,
  published_by jsonb,
  created_by jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX insight_template_snapshots_draft ON insight_template_snapshots (template_id) WHERE status = 'draft';
CREATE UNIQUE INDEX insight_template_snapshots_active ON insight_template_snapshots (template_id) WHERE status = 'active';

CREATE TABLE insight_template_sections (
  id uuid PRIMARY KEY,
  workspace_id uuid NOT NULL REFERENCES workspaces (id),
  snapshot_id uuid NOT NULL REFERENCES insight_template_snapshots (id),
  -- Rich-text documents (doc_type 'insight-section', parent_ref = this section): the title and the prompt.
  title_document_id uuid NOT NULL,
  prompt_document_id uuid NOT NULL,
  type text NOT NULL CHECK (type IN ('plaintext', 'list')),
  sort_order text COLLATE "C" NOT NULL,
  created_by jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz
);
CREATE INDEX insight_template_sections_snapshot ON insight_template_sections (snapshot_id, sort_order, id)
  WHERE deleted_at IS NULL;

CREATE TABLE insight_template_previews (
  id uuid PRIMARY KEY,                        -- client-minted ("Generate preview")
  workspace_id uuid NOT NULL REFERENCES workspaces (id),
  template_id uuid NOT NULL REFERENCES insight_templates (id),
  snapshot_id uuid NOT NULL REFERENCES insight_template_snapshots (id),
  recording_id uuid NOT NULL REFERENCES call_recordings (id),
  status text NOT NULL CHECK (status IN ('queued', 'executing', 'completed', 'failed')),
  -- [{sectionId, title, type, content, items}] in section order.
  sections jsonb NOT NULL DEFAULT '[]',
  error text,
  credit_cost integer NOT NULL DEFAULT 0,
  -- The draft's last_touched_at when the preview was requested: newer edits make the preview stale (Refresh).
  draft_touched_at timestamptz,
  requested_by_member_id uuid,
  created_by jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz
);
CREATE INDEX insight_template_previews_template ON insight_template_previews (template_id, created_at DESC);

CREATE TABLE call_insights (
  id uuid PRIMARY KEY,                        -- client-minted (choose template / Update)
  workspace_id uuid NOT NULL REFERENCES workspaces (id),
  recording_id uuid NOT NULL REFERENCES call_recordings (id),
  template_id uuid NOT NULL REFERENCES insight_templates (id),
  snapshot_id uuid NOT NULL REFERENCES insight_template_snapshots (id),
  status text NOT NULL CHECK (status IN ('queued', 'executing', 'completed', 'failed')),
  sections jsonb NOT NULL DEFAULT '[]',
  error text,
  credit_cost integer NOT NULL DEFAULT 0,
  input_tokens integer,
  output_tokens integer,
  -- Who pays (B.14): the requesting member; null = workspace (default template applied by the system).
  requested_by_member_id uuid,
  created_by jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz
);
CREATE INDEX call_insights_recording ON call_insights (recording_id, created_at DESC);
CREATE INDEX call_insights_template ON call_insights (template_id);
CREATE INDEX call_insights_spend ON call_insights (workspace_id, created_at) WHERE credit_cost > 0;

CREATE TABLE member_call_settings (
  member_id uuid PRIMARY KEY REFERENCES workspace_members (id),
  workspace_id uuid NOT NULL REFERENCES workspaces (id),
  default_insight_template_id uuid REFERENCES insight_templates (id),
  updated_at timestamptz NOT NULL DEFAULT now()
);

DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'call_speakers', 'insight_templates', 'insight_template_snapshots', 'insight_template_sections',
    'insight_template_previews', 'call_insights', 'member_call_settings'
  ] LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format(
      'CREATE POLICY tenant_isolation ON %I USING (workspace_id = app_workspace_id()) WITH CHECK (workspace_id = app_workspace_id())',
      t);
  END LOOP;
END
$$;
