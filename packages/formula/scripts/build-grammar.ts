// Compiles src/formula.grammar into src/parser.gen.ts + src/parser.terms.gen.ts (TypeScript, ES module).
// `pnpm --filter @agentic-crm/formula build:grammar`; test/grammar.test.ts fails when the committed files are stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildParserFile } from '@lezer/generator';

const SRC = join(dirname(fileURLToPath(import.meta.url)), '..', 'src');
const HEADER = '// GENERATED by scripts/build-grammar.ts from formula.grammar — do not edit.\n';

export function generateParser(): { parser: string; terms: string } {
  const grammar = readFileSync(join(SRC, 'formula.grammar'), 'utf8');
  const out = buildParserFile(grammar, { fileName: 'formula.grammar', typeScript: true, moduleStyle: 'es' });
  return {
    // The generated parser imports its terms from the conventional path; point it at the .gen file.
    parser: HEADER + out.parser.replace(/from "\.\/parser\.terms"/g, 'from "./parser.terms.gen.ts"'),
    terms: HEADER + out.terms,
  };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { parser, terms } = generateParser();
  writeFileSync(join(SRC, 'parser.gen.ts'), parser);
  writeFileSync(join(SRC, 'parser.terms.gen.ts'), terms);
  console.log('formula parser written');
}
